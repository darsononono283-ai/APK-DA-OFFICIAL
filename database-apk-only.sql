-- APK DA•OFFICIAL | Database katalog APK, unduhan, rating, ulasan, dan admin
-- Jalankan di Supabase SQL Editor. Script ini bersifat aditif untuk kolom apps.

create extension if not exists pgcrypto;

-- Akun yang boleh mengelola katalog harus terdaftar di tabel ini.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

-- Struktur dasar katalog APK.
create table if not exists public.apps (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text,
  description text not null default '',
  category text not null default 'Lainnya',
  developer text not null default '',
  version text not null default '',
  size text not null default '',
  icon text not null default '',
  download_url text not null default '',
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Tambahkan kolom yang dibutuhkan file website lama tanpa menghapus data lama.
alter table public.apps add column if not exists slug text;
alter table public.apps add column if not exists description text not null default '';
alter table public.apps add column if not exists category text not null default 'Lainnya';
alter table public.apps add column if not exists developer text not null default '';
alter table public.apps add column if not exists version text not null default '';
alter table public.apps add column if not exists size text not null default '';
alter table public.apps add column if not exists icon text not null default '';
alter table public.apps add column if not exists download_url text not null default '';
alter table public.apps add column if not exists is_published boolean not null default true;
alter table public.apps add column if not exists created_at timestamptz not null default now();
alter table public.apps add column if not exists updated_at timestamptz not null default now();

-- Kolom icon_url dan download_path dari skema lama tetap dibiarkan; halaman detail mendukung keduanya.

-- Buat slug yang belum ada. Slug baru dari admin juga diberi akhiran unik.
update public.apps
set slug = coalesce(nullif(trim(both '-' from regexp_replace(lower(coalesce(name,'apk')), '[^a-z0-9]+', '-', 'g')), ''), 'apk') || '-' || substr(md5(id::text),1,8)
where slug is null or btrim(slug) = '';
create unique index if not exists apps_slug_unique_idx on public.apps(slug);
create index if not exists apps_created_at_idx on public.apps(created_at desc);

-- Fungsi untuk memeriksa keanggotaan admin dari kebijakan RLS.
create or replace function public.is_site_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  );
$$;
revoke all on function public.is_site_admin() from public;
grant execute on function public.is_site_admin() to authenticated;

alter table public.admin_users enable row level security;
alter table public.apps enable row level security;

drop policy if exists "Admins read own membership" on public.admin_users;
create policy "Admins read own membership"
on public.admin_users for select to authenticated
using (user_id = (select auth.uid()));
grant select on public.admin_users to authenticated;

drop policy if exists "Public reads published apps" on public.apps;
drop policy if exists "Public reads apps" on public.apps;
create policy "Public reads apps"
on public.apps for select to anon, authenticated
using (true);

drop policy if exists "Admins insert apps" on public.apps;
create policy "Admins insert apps"
on public.apps for insert to authenticated
with check (public.is_site_admin());

drop policy if exists "Admins update apps" on public.apps;
create policy "Admins update apps"
on public.apps for update to authenticated
using (public.is_site_admin()) with check (public.is_site_admin());

drop policy if exists "Admins delete apps" on public.apps;
create policy "Admins delete apps"
on public.apps for delete to authenticated
using (public.is_site_admin());

grant select on public.apps to anon, authenticated;
grant insert, update, delete on public.apps to authenticated;

-- Statistik klik unduhan untuk halaman detail APK.
create table if not exists public.app_downloads (
  id bigint generated by default as identity primary key,
  app_id uuid not null references public.apps(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.app_downloads enable row level security;
drop policy if exists "Public read download counts" on public.app_downloads;
create policy "Public read download counts" on public.app_downloads for select to anon, authenticated using (true);
drop policy if exists "Public record download clicks" on public.app_downloads;
create policy "Public record download clicks" on public.app_downloads for insert to anon, authenticated with check (true);
grant select, insert on public.app_downloads to anon, authenticated;

-- Rating bintang dari pengunjung.
create table if not exists public.app_ratings (
  id bigint generated by default as identity primary key,
  app_id uuid not null references public.apps(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  voter_id text not null,
  created_at timestamptz not null default now(),
  unique (app_id, voter_id)
);
alter table public.app_ratings enable row level security;
drop policy if exists "Public read app ratings" on public.app_ratings;
create policy "Public read app ratings" on public.app_ratings for select to anon, authenticated using (true);
drop policy if exists "Public submit app ratings" on public.app_ratings;
create policy "Public submit app ratings" on public.app_ratings for insert to anon, authenticated with check (rating between 1 and 5 and length(voter_id) between 1 and 100);
grant select, insert on public.app_ratings to anon, authenticated;

-- Ulasan pengunjung. Status awal pending sehingga harus disetujui admin.
create table if not exists public.app_reviews (
  id bigint generated by default as identity primary key,
  app_id uuid not null references public.apps(id) on delete cascade,
  display_name text not null default 'Pengguna',
  review_text text not null,
  rating smallint not null check (rating between 1 and 5),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);
alter table public.app_reviews add column if not exists status text not null default 'pending';
alter table public.app_reviews enable row level security;
drop policy if exists "Public reads approved reviews" on public.app_reviews;
create policy "Public reads approved reviews" on public.app_reviews for select to anon, authenticated using (status = 'approved');
drop policy if exists "Admins read all reviews" on public.app_reviews;
create policy "Admins read all reviews" on public.app_reviews for select to authenticated using (public.is_site_admin());
drop policy if exists "Visitors submit pending reviews" on public.app_reviews;
create policy "Visitors submit pending reviews" on public.app_reviews for insert to anon, authenticated with check (status = 'pending' and rating between 1 and 5 and length(review_text) between 1 and 800);
drop policy if exists "Admins moderate reviews" on public.app_reviews;
create policy "Admins moderate reviews" on public.app_reviews for update to authenticated using (public.is_site_admin()) with check (public.is_site_admin());
drop policy if exists "Admins delete reviews" on public.app_reviews;
create policy "Admins delete reviews" on public.app_reviews for delete to authenticated using (public.is_site_admin());
grant select, insert on public.app_reviews to anon, authenticated;
grant update, delete on public.app_reviews to authenticated;

