-- Jalankan sekali di Supabase SQL Editor untuk mengaktifkan fitur Notifikasi.
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  title text not null,
  message text not null,
  created_at timestamptz not null default now()
);
alter table public.notifications enable row level security;

-- Pengunjung hanya boleh membaca pengumuman.
drop policy if exists "Public can read notifications" on public.notifications;
create policy "Public can read notifications"
on public.notifications for select to anon, authenticated using (true);

-- Hanya akun terautentikasi yang dapat mengelola pengumuman.
-- Jika proyek Anda memiliki sistem role admin, batasi policy ini lebih ketat.
drop policy if exists "Authenticated can insert notifications" on public.notifications;
create policy "Authenticated can insert notifications"
on public.notifications for insert to authenticated with check (true);

drop policy if exists "Authenticated can delete notifications" on public.notifications;
create policy "Authenticated can delete notifications"
on public.notifications for delete to authenticated using (true);
